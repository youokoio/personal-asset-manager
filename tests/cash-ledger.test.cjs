const assert = require('node:assert/strict');
const { cashEffect } = require('../finance-core.js');
const transferAdditional = {transactionType:'transfer',sourceAccountId:'bank',targetAccountId:'fx',amount:100000,feeAmount:220,feeMode:'additional',feeAccountId:'bank'};
assert.equal(cashEffect(transferAdditional,'bank'), -100220);
assert.equal(cashEffect(transferAdditional,'fx'), 100000);
const transferDeducted = {...transferAdditional,feeMode:'deducted'};
assert.equal(cashEffect(transferDeducted,'bank'), -100000);
assert.equal(cashEffect(transferDeducted,'fx'), 99780);
const deposit = {transactionType:'deposit',targetAccountId:'crypto',amount:100000,feeAmount:220,feeMode:'deducted',feeAccountId:'crypto'};
assert.equal(cashEffect(deposit,'crypto'), 99780);
const withdrawal = {transactionType:'withdrawal',sourceAccountId:'fx',amount:100000,feeAmount:220,feeMode:'additional',feeAccountId:'fx'};
assert.equal(cashEffect(withdrawal,'fx'), -100220);
const feeOnly = {transactionType:'fee',feeAmount:220,feeAccountId:'bank'};
assert.equal(cashEffect(feeOnly,'bank'), -220);
console.log('cash-ledger tests: 6 assertions passed');
const transferFeeOnTarget = {...transferAdditional, feeAccountId:'fx'};
assert.equal(cashEffect(transferFeeOnTarget,'bank'), -100000);
assert.equal(cashEffect(transferFeeOnTarget,'fx'), 99780);
const transferFeeOnThird = {...transferAdditional, feeAccountId:'bank2'};
assert.equal(cashEffect(transferFeeOnThird,'bank2'), -220);
assert.equal(cashEffect(transferFeeOnThird,'fx'), 100000);
const depositFeeOnThird = {...deposit, feeMode:'additional', feeAccountId:'bank'};
assert.equal(cashEffect(depositFeeOnThird,'crypto'), 100000);
assert.equal(cashEffect(depositFeeOnThird,'bank'), -220);
const withdrawalFeeOnThird = {...withdrawal, feeAccountId:'bank'};
assert.equal(cashEffect(withdrawalFeeOnThird,'fx'), -100000);
assert.equal(cashEffect(withdrawalFeeOnThird,'bank'), -220);
console.log('additional fee-allocation tests: 8 assertions passed');
